const router = require('express').Router();
const rateLimit = require('express-rate-limit');
const auth = require('../controllers/auth.controller');
const task = require('../controllers/task.controller');
const admin = require('../controllers/admin.controller');
const project = require('../controllers/project.controller');
const publicController = require('../controllers/public.controller');
const onboarding = require('../controllers/onboarding.controller');
const collaboration = require('../controllers/collaboration.controller');
const { authenticate, authorize } = require('../middleware/auth');
// A shared browser/Nginx address can legitimately cover multiple local users.
// Keep a meaningful brute-force guard without blocking the complete browser workflow.
const authLimit = rateLimit({ windowMs: 15 * 60 * 1000, max: 100, standardHeaders: true, legacyHeaders: false, skip: () => process.env.NODE_ENV === 'test', message: { message: 'Too many authentication attempts. Please try again later.' } });

router.get('/health', (_, res) => res.json({ status: 'ok', service: 'zeeman-api', timestamp: new Date().toISOString() }));
router.post('/contact', authLimit, publicController.contact);
router.post('/auth/register', authLimit, auth.register);
router.post('/auth/login', authLimit, auth.login);
router.post('/auth/forgot-password', authLimit, auth.forgotPassword);
router.post('/auth/reset-password', authLimit, auth.resetPassword);
router.post('/auth/verify-email', authLimit, auth.verifyEmail);
router.post('/auth/logout', authenticate, auth.logout);
router.get('/auth/me', authenticate, auth.me);
router.put('/auth/profile', authenticate, auth.updateProfile);
router.put('/auth/password', authenticate, auth.updatePassword);
router.post('/auth/resend-verification', authenticate, authLimit, auth.resendVerification);
router.get('/auth/onboarding', authenticate, onboarding.status);
router.put('/auth/onboarding/profile', authenticate, onboarding.profile);
router.post('/auth/onboarding/complete', authenticate, onboarding.complete);
router.get('/projects', authenticate, project.list);
router.get('/projects/:id', authenticate, project.getOne);
router.get('/projects/:id/tasks', authenticate, project.tasks);
router.get('/projects/:id/activity', authenticate, authorize('admin'), project.activity);
router.post('/projects', authenticate, authorize('admin'), project.create);
router.put('/projects/:id', authenticate, authorize('admin'), project.update);
router.patch('/projects/:id', authenticate, authorize('admin'), project.update);
router.post('/projects/:id/archive', authenticate, authorize('admin'), project.archive);
router.post('/projects/:id/restore', authenticate, authorize('admin'), project.restore);
router.delete('/projects/:id', authenticate, authorize('admin'), project.remove);
router.get('/projects/:id/members', authenticate, project.members);
router.post('/projects/:id/members', authenticate, authorize('admin'), project.addMember);
router.delete('/projects/:id/members/:userId', authenticate, authorize('admin'), project.removeMember);
router.get('/tasks', authenticate, task.list);
router.get('/tasks/:id', authenticate, task.getOne);
router.post('/tasks', authenticate, authorize('admin'), task.create);
router.put('/tasks/:id', authenticate, authorize('admin'), task.update);
router.patch('/tasks/:id', authenticate, authorize('admin'), task.update);
router.patch('/tasks/:id/status', authenticate, task.updateStatus);
router.delete('/tasks/:id', authenticate, authorize('admin'), task.remove);
router.get('/tasks/:taskId/comments', authenticate, collaboration.comments);
router.post('/tasks/:taskId/comments', authenticate, collaboration.createComment);
router.patch('/comments/:id', authenticate, collaboration.updateComment);
router.delete('/comments/:id', authenticate, collaboration.deleteComment);
router.get('/tasks/:taskId/mentionable-users', authenticate, collaboration.mentionable);
router.get('/tasks/:taskId/subtasks', authenticate, collaboration.subtasks);
router.post('/tasks/:taskId/subtasks', authenticate, collaboration.createSubtask);
router.patch('/subtasks/:id/status', authenticate, collaboration.updateSubtaskStatus);
router.delete('/subtasks/:id', authenticate, collaboration.deleteSubtask);
router.get('/tasks/:taskId/checklists', authenticate, collaboration.checklist);
router.post('/tasks/:taskId/checklists', authenticate, collaboration.createChecklist);
router.patch('/checklist-items/:id/completion', authenticate, collaboration.completeChecklist);
router.get('/tasks/:taskId/activity', authenticate, collaboration.activity);
router.get('/tasks/:taskId/attachments', authenticate, collaboration.attachments);
router.post('/tasks/:taskId/attachments', authenticate, collaboration.uploadAttachment);
router.get('/attachments/:id/download', authenticate, collaboration.downloadAttachment);
router.delete('/attachments/:id', authenticate, collaboration.deleteAttachment);
router.get('/categories', authenticate, admin.listCategories);
router.get('/analytics/user', authenticate, admin.userAnalytics);
router.get('/reports/user', authenticate, admin.userReport);
router.get('/notifications', authenticate, admin.listNotifications);
router.patch('/notifications/:id', authenticate, admin.updateNotification);
router.post('/notifications/read-all', authenticate, admin.readAllNotifications);
router.put('/preferences', authenticate, auth.updateProfile);
router.post('/sessions/logout-others', authenticate, admin.logoutOtherSessions);
router.use('/admin', authenticate, authorize('admin'));
router.get('/admin/users', admin.listUsers);
router.get('/admin/users/:id', admin.getUser);
router.post('/admin/users', admin.createUser);
router.put('/admin/users/:id', admin.updateUser);
router.delete('/admin/users/:id', admin.deleteUser);
router.get('/admin/tasks', task.list);
router.post('/admin/tasks', task.create);
router.put('/admin/tasks/:id', task.update);
router.patch('/admin/tasks/:id', task.update);
router.patch('/admin/tasks/:id/assignee', task.update);
router.delete('/admin/tasks/:id', task.remove);
