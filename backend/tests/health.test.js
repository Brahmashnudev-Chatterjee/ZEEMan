const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const testDb = path.join(os.tmpdir(), `zeeman-test-${process.pid}.db`);
process.env.DATABASE_PATH = testDb;
const request = require('supertest');
const app = require('../src/app');
const { initializeDatabase } = require('../src/config/database');
const uniqueEmail = () => `test-${Date.now()}-${Math.random().toString(16).slice(2)}@example.test`;
test.after(() => { for (const suffix of ['', '-shm', '-wal']) { try { fs.unlinkSync(`${testDb}${suffix}`); } catch (_) {} } });
test('health endpoint responds', async () => { const response = await request(app).get('/api/health'); assert.equal(response.status, 200); assert.equal(response.body.status, 'ok'); });
test('public contact form accepts valid submissions and rejects incomplete input', async () => {
  await initializeDatabase();
  const accepted = await request(app).post('/api/contact').set('Origin', 'http://localhost:3000').send({ name: 'Website Visitor', email: 'visitor@example.test', subject: 'Interested in ZeeMan', message: 'Please tell me more about project collaboration.' });
  assert.equal(accepted.status, 201);
  const rejected = await request(app).post('/api/contact').set('Origin', 'http://localhost:3000').send({ name: 'Website Visitor' });
  assert.equal(rejected.status, 400);
});
test('regular users cannot access another user task or admin routes', async () => {
  await initializeDatabase();
  const firstAgent = request.agent(app);
  const secondAgent = request.agent(app);
  const first = await firstAgent.post('/api/auth/register').set('Origin', 'http://localhost:3000').send({ name: 'First User', email: uniqueEmail(), password: 'SafePassword_2026' });
  const second = await secondAgent.post('/api/auth/register').set('Origin', 'http://localhost:3000').send({ name: 'Second User', email: uniqueEmail(), password: 'OtherPassword_2026' });
  assert.equal(first.status, 201);
  assert.equal(second.status, 201);
  const task = await firstAgent.post('/api/tasks').set('Origin', 'http://localhost:3000').send({ title: 'Private task', priority: 'high' });
  assert.equal(task.status, 201);
  const forbiddenTask = await secondAgent.get(`/api/tasks/${task.body.task.id}`);
  assert.equal(forbiddenTask.status, 404);
  const forbiddenAdmin = await firstAgent.get('/api/admin/users');
  assert.equal(forbiddenAdmin.status, 403);
});
test('project members can access shared project tasks but unrelated users cannot', async () => {
  await initializeDatabase();
  const owner = request.agent(app); const member = request.agent(app); const outsider = request.agent(app);
  const ownerAccount = await owner.post('/api/auth/register').set('Origin', 'http://localhost:3000').send({ name: 'Project Owner', email: uniqueEmail(), password: 'OwnerPassword_2026' });
  const memberAccount = await member.post('/api/auth/register').set('Origin', 'http://localhost:3000').send({ name: 'Project Member', email: uniqueEmail(), password: 'MemberPassword_2026' });
  const outsiderAccount = await outsider.post('/api/auth/register').set('Origin', 'http://localhost:3000').send({ name: 'Project Outsider', email: uniqueEmail(), password: 'OutsidePassword_2026' });
  const project = await owner.post('/api/projects').set('Origin', 'http://localhost:3000').send({ name: 'Shared project', status: 'active' });
  assert.equal(project.status, 201);
  const addMember = await owner.post(`/api/projects/${project.body.project.id}/members`).set('Origin', 'http://localhost:3000').send({ user_id: memberAccount.body.user.id });
  assert.equal(addMember.status, 201);
  const task = await owner.post('/api/tasks').set('Origin', 'http://localhost:3000').send({ title: 'Shared task', project_id: project.body.project.id, priority: 'high' });
  assert.equal(task.status, 201);
  assert.equal((await member.get(`/api/tasks/${task.body.task.id}`)).status, 200);
  assert.equal((await outsider.get(`/api/tasks/${task.body.task.id}`)).status, 404);
  assert.ok(outsiderAccount.body.user.id);
});
